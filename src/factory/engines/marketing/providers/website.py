"""Web-search-driven contact scraping, verified via Hunter's Email Finder.

Ported from a proven, already-in-production reference (`reference files/
lead_scout.py`, a Lead Scout agent for a different product) rather than designed
from scratch — that file has real, documented production lessons baked into it (a
domain-matching bug that would have emailed a LinkedIn employee, a company-name
dedup bug, wasted spend from re-scraping the same directory). This module ports its
proven mechanisms, replacing only what was genuinely specific to that one product's
audience (a hand-written ICP prompt) with a per-product `QualificationBrief`
generated by `leads.py::build_qualification_brief`.

Unlike Apollo/Hunter's domain-search, this provider needs three things they don't:
a `FactoryContext` (LLM calls for query generation and extraction), a DB session
(the dedup/cooldown checks below), and the product's own summary text. It is
constructed directly by `leads.py::_real_adapters` with all three — see that
module's docstring for why `providers/__init__.py::build_providers()` does not
construct it.
"""

